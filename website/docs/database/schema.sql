-- =============================================================================
-- uniFITS — Database Schema v2.4 (REFERENCE — not applied to any database yet)
-- PostgreSQL 15+ · Multi-tenant · derived from the owner's v2.0 draft
-- Tested on PostgreSQL 16: loads clean, behaviour proven by schema.tests.sql
-- =============================================================================
-- CHANGES vs v2.0 (each one fixes something verified by running the draft):
--  1. Tenant isolation in the DB: every tenant table has UNIQUE (org_id, id) and every
--     reference to a tenant table is a composite FK (org_id, x_id) -> no cross-org links.
--  2. Soft delete: unique rules are partial indexes (WHERE deleted_at IS NULL), email/username
--     compared case-insensitively. No SET NULL on tenant FKs: data is soft-deleted, never hard-deleted.
--  3. One active role per user (partial unique index) + is_active must match removed_at.
--  4. Approvals: approval_status + reviewed_by/at (+ rejection_reason) on projects, events;
--     transactions.status = pending/approved/rejected/voided. A trigger enforces WHO may review
--     (approve_* permission) and who may review their OWN entries (approve_own_entries).
--  5. Transactions: exactly one context FK per category; contribution needs a member;
--     opening_balance entry type; 'returned' -> 'refund'; direction defined by signed_amount().
--     transaction_date / received_date are DATE (Manila day cannot shift); reference_number is
--     generated by a trigger (TXN-YYYYMMDD-NNNNNN).
--  6. Utilities are a BILL (total, due date); payments are ledger transactions (category 'utility').
--     amount_paid and status are DERIVED (view utility_balances) -> cannot contradict each other.
--  7. Balances/funding are never stored: views fund_balances, project_financials, event_financials
--     count approved transactions only.
--  8. attendances: unique per person + activity + date.
--  9. Added: organizations plural labels, events.event_type, projects/events.photo_url,
--     users.joined_date, user_status 'inactive', audit actions approve/reject/void,
--     permissions aligned with the frontend (37 keys), seed_org_defaults() for roles/permissions/methods.
-- 10. Removed: funds.currency (the org currency applies), 'paid' transaction status.
-- 11. transactions: description (list title) + notes replace remarks, matching the frontend Transaction type.
-- v2.2 (owner decisions: approved entries must never be tampered with; a fund may never go below zero):
-- 12. Ledger immutability (trigger): a PENDING entry may be corrected or deleted; once APPROVED, only a note can be
--     added or the entry can be VOIDED (voided_by, voided_at, void_reason recorded); REJECTED and VOIDED entries are
--     frozen; approved entries can never be edited, soft-deleted or hard-deleted. Corrections = void + new entry.
-- 13. Overdraft guard (trigger): approving an expense/refund, or voiding an approved inflow, is rejected when it would
--     take the fund below zero (down to exactly 0 is allowed). The fund row is locked first, so two simultaneous
--     approvals cannot both pass. fund_balance(fund_id) is the function form of the fund_balances view.
-- v2.3 (owner decision: officers must review and approve first — restriction and discipline):
-- 14. Approved-activity guard (triggers): a transaction or an attendance record can only point at a project/event whose
--     approval_status is 'approved'. Checked when the row is created, when it is re-pointed to another project/event, and when a
--     pending transaction is being approved. History stays editable: voiding an approved transaction and correcting existing
--     attendance still work after a project is later rejected. (An approved project can still be set to rejected afterwards —
--     not blocked yet; ask the owner whether approval decisions should be final.)
-- v2.4 (project/event funding is DERIVED, like fund balances):
-- 15. An opening_balance entry may also belong to a project or event ("funding raised before the system started"): it needs the
--     project/event, no member, and NO fund (so no fund balance changes). Views project_financials / event_financials gain
--     opening_balance, refunds and funding_raised = contributions + external income + opening - refunds (approved only;
--     expenses never reduce funding raised; owner confirmed refunds do).
-- Auth tables/columns (password_hash, tokens, sessions, login_attempts) are kept as in v2.0 but
-- are marked "AUTH" — their fate depends on the Supabase decision (not made yet).
-- =============================================================================

CREATE EXTENSION IF NOT EXISTS "pgcrypto";

-- ===== ENUM TYPES =====
CREATE TYPE org_plan_enum           AS ENUM ('standard', 'premium');
CREATE TYPE org_status_enum         AS ENUM ('active', 'suspended', 'cancelled');
CREATE TYPE user_status_enum        AS ENUM ('active', 'inactive', 'delinquent', 'suspended', 'expelled');
CREATE TYPE lifecycle_status_enum   AS ENUM ('upcoming', 'ongoing', 'completed', 'cancelled');   -- projects + events
CREATE TYPE approval_status_enum    AS ENUM ('pending', 'approved', 'rejected');
CREATE TYPE activity_type_enum      AS ENUM ('project', 'event');
CREATE TYPE attendance_status_enum  AS ENUM ('present', 'absent', 'late', 'excused');
CREATE TYPE fund_type_enum          AS ENUM ('internal', 'external');
CREATE TYPE fund_status_enum        AS ENUM ('active', 'inactive');
CREATE TYPE payment_freq_enum       AS ENUM ('monthly', 'quarterly', 'annually');
-- inflow: income, contribution, opening_balance · outflow: expense, refund
CREATE TYPE transaction_entry_enum  AS ENUM ('income', 'expense', 'contribution', 'refund', 'opening_balance');
CREATE TYPE transaction_cat_enum    AS ENUM ('project', 'event', 'utility', 'fund');
CREATE TYPE transaction_status_enum AS ENUM ('pending', 'approved', 'rejected', 'voided');
CREATE TYPE audit_action_enum       AS ENUM ('insert', 'update', 'delete', 'approve', 'reject', 'void', 'login', 'logout', 'export', 'backup', 'restore');
CREATE TYPE backup_job_type_enum    AS ENUM ('backup', 'restore');
CREATE TYPE backup_trigger_enum     AS ENUM ('manual', 'scheduled', 'pre_update');
CREATE TYPE backup_status_enum      AS ENUM ('pending', 'running', 'success', 'failed');
CREATE TYPE backup_freq_enum        AS ENUM ('daily', 'weekly', 'monthly');

-- ===== 1. organizations =====
CREATE TABLE organizations (
    id                  UUID            PRIMARY KEY DEFAULT gen_random_uuid(),
    name                VARCHAR(255)    NOT NULL,
    slug                VARCHAR(100)    NOT NULL UNIQUE,
    logo_url            VARCHAR(500),
    currency_code       VARCHAR(10)     NOT NULL DEFAULT 'PHP',
    currency_symbol     VARCHAR(5)      NOT NULL DEFAULT '₱',
    timezone            VARCHAR(50)     NOT NULL DEFAULT 'Asia/Manila',
    date_format         VARCHAR(30)     NOT NULL DEFAULT 'DD/MM/YYYY',
    plan                org_plan_enum   NOT NULL DEFAULT 'standard',
    status              org_status_enum NOT NULL DEFAULT 'active',
    -- Terminology: singular + plural stored, so the UI never builds "Utilitys"
    people_label        VARCHAR(50)     NOT NULL DEFAULT 'Member',
    people_label_plural VARCHAR(50)     NOT NULL DEFAULT 'Members',
    project_label       VARCHAR(50)     NOT NULL DEFAULT 'Project',
    project_label_plural VARCHAR(50)    NOT NULL DEFAULT 'Projects',
    event_label         VARCHAR(50)     NOT NULL DEFAULT 'Event',
    event_label_plural  VARCHAR(50)     NOT NULL DEFAULT 'Events',
    fund_label          VARCHAR(50)     NOT NULL DEFAULT 'Fund',
    fund_label_plural   VARCHAR(50)     NOT NULL DEFAULT 'Funds',
    transaction_label   VARCHAR(50)     NOT NULL DEFAULT 'Transaction',
    transaction_label_plural VARCHAR(50) NOT NULL DEFAULT 'Transactions',
    utility_label       VARCHAR(50)     NOT NULL DEFAULT 'Utility',
    utility_label_plural VARCHAR(50)    NOT NULL DEFAULT 'Utilities',
    attendance_label    VARCHAR(50)     NOT NULL DEFAULT 'Attendance',
    attendance_label_plural VARCHAR(50) NOT NULL DEFAULT 'Attendance',
    report_label        VARCHAR(50)     NOT NULL DEFAULT 'Report',
    report_label_plural VARCHAR(50)     NOT NULL DEFAULT 'Reports',
    created_at          TIMESTAMPTZ     NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ     NOT NULL DEFAULT NOW()
);
CREATE INDEX idx_organizations_status ON organizations (status);

-- ===== 2. users (UI shows the org's people_label) =====
CREATE TABLE users (
    id                  UUID                PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id              UUID                NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    employee_number     VARCHAR(30)         NOT NULL,
    first_name          VARCHAR(100)        NOT NULL,
    middle_name         VARCHAR(100),
    last_name           VARCHAR(100)        NOT NULL,
    date_of_birth       DATE                NOT NULL,
    gender              VARCHAR(20)         NOT NULL,
    contact_number      VARCHAR(20)         NOT NULL,
    email               VARCHAR(255)        NOT NULL,
    username            VARCHAR(150)        NOT NULL,
    address_street      VARCHAR(255),
    address_barangay    VARCHAR(100),
    address_city        VARCHAR(100),
    address_province    VARCHAR(100),
    occupation          VARCHAR(150),
    department          VARCHAR(100),
    photo_url           VARCHAR(500),
    joined_date         DATE                NOT NULL DEFAULT CURRENT_DATE,   -- membership/employment start (frontend "joined")
    has_partner         BOOLEAN             NOT NULL DEFAULT FALSE,
    anniversary_date    DATE,
    status              user_status_enum    NOT NULL DEFAULT 'active',
    -- AUTH (kept from v2.0; revisit in the Supabase discussion)
    password_hash       VARCHAR(255)        NOT NULL,
    is_verified         BOOLEAN             NOT NULL DEFAULT FALSE,
    verification_token  VARCHAR(255),
    reset_token_hash    VARCHAR(255),
    reset_token_expires TIMESTAMPTZ,
    last_login_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ         NOT NULL DEFAULT NOW(),
    updated_at          TIMESTAMPTZ         NOT NULL DEFAULT NOW(),
    deleted_at          TIMESTAMPTZ,
    UNIQUE (org_id, id),                                                   -- target of composite FKs
    CONSTRAINT chk_anniversary CHECK (has_partner = TRUE OR anniversary_date IS NULL)
);
-- Unique only among live rows; email/username case-insensitive
CREATE UNIQUE INDEX uq_users_employee_number ON users (org_id, employee_number) WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_users_email           ON users (org_id, lower(email))    WHERE deleted_at IS NULL;
CREATE UNIQUE INDEX uq_users_username        ON users (org_id, lower(username)) WHERE deleted_at IS NULL;
CREATE INDEX idx_users_status ON users (org_id, status) WHERE deleted_at IS NULL;

-- ===== 3. roles =====
CREATE TABLE roles (
    id          UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID         NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    name        VARCHAR(100) NOT NULL,
    description TEXT,
    is_system   BOOLEAN      NOT NULL DEFAULT FALSE,   -- system roles cannot be deleted
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    UNIQUE (org_id, id),
    UNIQUE (org_id, name)
);

-- ===== 4. user_roles (history; exactly one active role per user) =====
CREATE TABLE user_roles (
    id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID        NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    user_id     UUID        NOT NULL,
    role_id     UUID        NOT NULL,
    is_active   BOOLEAN     NOT NULL DEFAULT TRUE,
    assigned_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    removed_at  TIMESTAMPTZ,
    assigned_by UUID        NOT NULL,
    FOREIGN KEY (org_id, user_id)     REFERENCES users (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, role_id)     REFERENCES roles (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, assigned_by) REFERENCES users (org_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_user_role_active CHECK (is_active = (removed_at IS NULL))
);
CREATE UNIQUE INDEX uq_user_roles_one_active ON user_roles (user_id) WHERE is_active;
CREATE INDEX idx_user_roles_role ON user_roles (role_id) WHERE is_active;

-- ===== 5. permissions (global, seeded once) =====
CREATE TABLE permissions (
    id          UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    key         VARCHAR(100) NOT NULL UNIQUE,
    label       VARCHAR(150) NOT NULL,
    module      VARCHAR(50)  NOT NULL,
    description TEXT
);
CREATE INDEX idx_permissions_module ON permissions (module);

-- ===== 6. role_permissions =====
CREATE TABLE role_permissions (
    role_id       UUID NOT NULL REFERENCES roles (id)       ON DELETE CASCADE,
    permission_id UUID NOT NULL REFERENCES permissions (id) ON DELETE CASCADE,
    PRIMARY KEY (role_id, permission_id)
);

-- ===== 7. announcements =====
CREATE TABLE announcements (
    id          UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id      UUID         NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    title       VARCHAR(255) NOT NULL,
    body        TEXT         NOT NULL,
    image_url   VARCHAR(500),
    is_pinned   BOOLEAN      NOT NULL DEFAULT FALSE,
    expires_at  TIMESTAMPTZ,
    created_by  UUID         NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    deleted_at  TIMESTAMPTZ,
    FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE RESTRICT
);
CREATE INDEX idx_announcements_org ON announcements (org_id) WHERE deleted_at IS NULL;

-- ===== 8. projects =====
CREATE TABLE projects (
    id               UUID                  PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id           UUID                  NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    title            VARCHAR(255)          NOT NULL,
    description      TEXT,
    project_type     VARCHAR(100),
    target_funding   NUMERIC(15,2)         NOT NULL DEFAULT 0,       -- raised amount is DERIVED (project_financials)
    start_date       DATE                  NOT NULL,
    end_date         DATE,
    location         VARCHAR(255),
    photo_url        VARCHAR(500),
    status           lifecycle_status_enum NOT NULL DEFAULT 'upcoming',
    approval_status  approval_status_enum  NOT NULL DEFAULT 'pending',
    reviewed_by      UUID,
    reviewed_at      TIMESTAMPTZ,
    rejection_reason TEXT,
    created_by       UUID                  NOT NULL,
    created_at       TIMESTAMPTZ           NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ           NOT NULL DEFAULT NOW(),
    deleted_at       TIMESTAMPTZ,
    UNIQUE (org_id, id),
    FOREIGN KEY (org_id, created_by)  REFERENCES users (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, reviewed_by) REFERENCES users (org_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_project_dates  CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT chk_project_target CHECK (target_funding >= 0),
    CONSTRAINT chk_project_review CHECK (
        (approval_status = 'pending'  AND reviewed_by IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL) OR
        (approval_status = 'approved' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NULL) OR
        (approval_status = 'rejected' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);
CREATE INDEX idx_projects_org    ON projects (org_id, status) WHERE deleted_at IS NULL;
CREATE INDEX idx_projects_review ON projects (org_id, approval_status) WHERE deleted_at IS NULL;

-- ===== 9. events =====
CREATE TABLE events (
    id               UUID                  PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id           UUID                  NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    title            VARCHAR(255)          NOT NULL,
    description      TEXT,
    event_type       VARCHAR(100),                                    -- replaces the title-keyword guess (bug B-74)
    target_funding   NUMERIC(15,2)         NOT NULL DEFAULT 0,
    event_date       DATE                  NOT NULL,
    event_time       TIME,
    location         VARCHAR(255),
    photo_url        VARCHAR(500),
    status           lifecycle_status_enum NOT NULL DEFAULT 'upcoming',
    approval_status  approval_status_enum  NOT NULL DEFAULT 'pending',
    reviewed_by      UUID,
    reviewed_at      TIMESTAMPTZ,
    rejection_reason TEXT,
    created_by       UUID                  NOT NULL,
    created_at       TIMESTAMPTZ           NOT NULL DEFAULT NOW(),
    updated_at       TIMESTAMPTZ           NOT NULL DEFAULT NOW(),
    deleted_at       TIMESTAMPTZ,
    UNIQUE (org_id, id),
    FOREIGN KEY (org_id, created_by)  REFERENCES users (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, reviewed_by) REFERENCES users (org_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_event_target CHECK (target_funding >= 0),
    CONSTRAINT chk_event_review CHECK (
        (approval_status = 'pending'  AND reviewed_by IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL) OR
        (approval_status = 'approved' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NULL) OR
        (approval_status = 'rejected' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL))
);
CREATE INDEX idx_events_org    ON events (org_id, event_date) WHERE deleted_at IS NULL;
CREATE INDEX idx_events_review ON events (org_id, approval_status) WHERE deleted_at IS NULL;

-- ===== 10. attendances =====
CREATE TABLE attendances (
    id              UUID                   PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id          UUID                   NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    user_id         UUID                   NOT NULL,
    activity_type   activity_type_enum     NOT NULL,
    project_id      UUID,
    event_id        UUID,
    attendance_date DATE                   NOT NULL,
    status          attendance_status_enum NOT NULL,
    remarks         TEXT,
    recorded_by     UUID                   NOT NULL,
    created_at      TIMESTAMPTZ            NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ            NOT NULL DEFAULT NOW(),
    FOREIGN KEY (org_id, user_id)     REFERENCES users    (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, project_id)  REFERENCES projects (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, event_id)    REFERENCES events   (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, recorded_by) REFERENCES users    (org_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_attendance_activity CHECK (
        (project_id IS NOT NULL AND event_id IS NULL AND activity_type = 'project') OR
        (event_id IS NOT NULL AND project_id IS NULL AND activity_type = 'event'))
);
CREATE UNIQUE INDEX uq_attendance_project ON attendances (user_id, project_id, attendance_date) WHERE project_id IS NOT NULL;
CREATE UNIQUE INDEX uq_attendance_event   ON attendances (user_id, event_id,   attendance_date) WHERE event_id   IS NOT NULL;
CREATE INDEX idx_attendances_org ON attendances (org_id);

-- ===== 11. funds (balance DERIVED — view fund_balances) =====
CREATE TABLE funds (
    id                UUID             PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id            UUID             NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    name              VARCHAR(255)     NOT NULL,
    description       TEXT,
    fund_type         fund_type_enum   NOT NULL,
    status            fund_status_enum NOT NULL DEFAULT 'active',
    is_required       BOOLEAN          NOT NULL DEFAULT FALSE,
    payment_frequency payment_freq_enum,
    annual_fee        NUMERIC(15,2),
    created_by        UUID             NOT NULL,
    created_at        TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ      NOT NULL DEFAULT NOW(),
    deleted_at        TIMESTAMPTZ,
    UNIQUE (org_id, id),
    FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_fund_required_fields CHECK (
        (is_required = TRUE  AND payment_frequency IS NOT NULL AND annual_fee IS NOT NULL AND annual_fee > 0) OR
        (is_required = FALSE AND payment_frequency IS NULL     AND annual_fee IS NULL))
);
CREATE UNIQUE INDEX uq_funds_name ON funds (org_id, lower(name)) WHERE deleted_at IS NULL;

-- ===== 12. payment_methods =====
CREATE TABLE payment_methods (
    id         UUID         PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id     UUID         NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    name       VARCHAR(100) NOT NULL,
    is_active  BOOLEAN      NOT NULL DEFAULT TRUE,
    sort_order INT          NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT NOW(),
    UNIQUE (org_id, id),
    UNIQUE (org_id, name)
);

-- ===== 13. utilities = the BILL. Payments are transactions (category 'utility') =====
CREATE TABLE utilities (
    id           UUID          PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id       UUID          NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    expense_type VARCHAR(100)  NOT NULL,
    total_amount NUMERIC(15,2) NOT NULL,
    due_date     DATE          NOT NULL,                      -- was payment_date (ambiguous)
    paid_to      VARCHAR(255),
    notes        TEXT,
    fund_id      UUID,                                         -- fund that covers this bill
    created_by   UUID          NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT NOW(),
    deleted_at   TIMESTAMPTZ,
    UNIQUE (org_id, id),
    FOREIGN KEY (org_id, fund_id)    REFERENCES funds (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, created_by) REFERENCES users (org_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_utility_total CHECK (total_amount > 0)
);
CREATE INDEX idx_utilities_org ON utilities (org_id) WHERE deleted_at IS NULL;

-- ===== 14. transactions — the single ledger =====
CREATE SEQUENCE transaction_ref_seq;

CREATE TABLE transactions (
    id                UUID                    PRIMARY KEY DEFAULT gen_random_uuid(),
    org_id            UUID                    NOT NULL REFERENCES organizations (id) ON DELETE RESTRICT,
    reference_number  VARCHAR(50)             NOT NULL,                 -- set by trigger when omitted
    entry_type        transaction_entry_enum  NOT NULL,
    amount            NUMERIC(15,2)           NOT NULL,                 -- always > 0; entry_type gives direction
    payment_method_id UUID,
    category          transaction_cat_enum    NOT NULL,
    user_id           UUID,                                             -- member (null = external)
    external_source   VARCHAR(255),
    fund_id           UUID,                                             -- fund affected (required when category = 'fund')
    project_id        UUID,
    event_id          UUID,
    utility_id        UUID,
    description       VARCHAR(255)            NOT NULL DEFAULT '',     -- short title shown in lists
    notes             TEXT,                                             -- optional free-text note
    status            transaction_status_enum NOT NULL DEFAULT 'pending',
    reviewed_by       UUID,
    reviewed_at       TIMESTAMPTZ,
    rejection_reason  TEXT,
    voided_by         UUID,                                             -- who voided it (status 'voided' only)
    voided_at         TIMESTAMPTZ,
    void_reason       TEXT,
    transaction_date  DATE                    NOT NULL,                 -- DATE: a Manila day cannot shift
    received_date     DATE,
    created_by        UUID                    NOT NULL,
    created_at        TIMESTAMPTZ             NOT NULL DEFAULT NOW(),
    updated_at        TIMESTAMPTZ             NOT NULL DEFAULT NOW(),
    deleted_at        TIMESTAMPTZ,
    UNIQUE (org_id, reference_number),
    FOREIGN KEY (org_id, payment_method_id) REFERENCES payment_methods (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, user_id)           REFERENCES users           (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, fund_id)           REFERENCES funds           (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, project_id)        REFERENCES projects        (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, event_id)          REFERENCES events          (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, utility_id)        REFERENCES utilities       (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, created_by)        REFERENCES users           (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, reviewed_by)       REFERENCES users           (org_id, id) ON DELETE RESTRICT,
    FOREIGN KEY (org_id, voided_by)         REFERENCES users           (org_id, id) ON DELETE RESTRICT,
    CONSTRAINT chk_tx_amount  CHECK (amount > 0),
    -- Exactly the context FK that matches the category (fund_id may accompany project/event/utility)
    CONSTRAINT chk_tx_context CHECK (
        (category = 'project' AND project_id IS NOT NULL AND event_id IS NULL     AND utility_id IS NULL) OR
        (category = 'event'   AND event_id   IS NOT NULL AND project_id IS NULL   AND utility_id IS NULL) OR
        (category = 'utility' AND utility_id IS NOT NULL AND project_id IS NULL   AND event_id IS NULL)   OR
        (category = 'fund'    AND fund_id    IS NOT NULL AND project_id IS NULL   AND event_id IS NULL AND utility_id IS NULL)),
    CONSTRAINT chk_tx_party        CHECK (user_id IS NULL OR external_source IS NULL),
    CONSTRAINT chk_tx_contribution CHECK (entry_type <> 'contribution' OR user_id IS NOT NULL),
    CONSTRAINT chk_tx_opening      CHECK (entry_type <> 'opening_balance' OR (category IN ('fund', 'project', 'event') AND user_id IS NULL AND external_source IS NULL AND (category = 'fund' OR fund_id IS NULL))),
    CONSTRAINT chk_tx_utility_type CHECK (category <> 'utility' OR entry_type IN ('expense', 'refund')),
    CONSTRAINT chk_tx_review CHECK (
        (status = 'pending'  AND reviewed_by IS NULL AND reviewed_at IS NULL AND rejection_reason IS NULL) OR
        (status = 'approved' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL AND rejection_reason IS NULL) OR
        (status = 'rejected' AND reviewed_by IS NOT NULL AND reviewed_at IS NOT NULL) OR
        (status = 'voided')),
    CONSTRAINT chk_tx_void CHECK (
        (status = 'voided'  AND voided_by IS NOT NULL AND voided_at IS NOT NULL) OR
        (status <> 'voided' AND voided_by IS NULL AND voided_at IS NULL AND void_reason IS NULL))
);
CREATE INDEX idx_tx_fund    ON transactions (fund_id)    WHERE deleted_at IS NULL;
CREATE INDEX idx_tx_user    ON transactions (user_id)    WHERE deleted_at IS NULL;
CREATE INDEX idx_tx_project ON transactions (project_id) WHERE project_id IS NOT NULL AND deleted_at IS NULL;
CREATE INDEX idx_tx_event   ON transactions (event_id)   WHERE event_id   IS NOT NULL AND deleted_at IS NULL;
