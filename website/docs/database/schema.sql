-- signed_amount — the ONE direction rule: inflow +, outflow -
CREATE OR REPLACE FUNCTION signed_amount(p_type transaction_entry_enum, p_amount NUMERIC) RETURNS NUMERIC
LANGUAGE sql IMMUTABLE AS $$
    SELECT CASE WHEN p_type IN ('income', 'contribution', 'opening_balance') THEN p_amount ELSE -p_amount END;
$$;

-- enforce_approved_activity — money and attendance only for APPROVED projects/events
CREATE OR REPLACE FUNCTION enforce_approved_activity() RETURNS TRIGGER AS $$
DECLARE
    v_becoming_approved BOOLEAN := FALSE;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        -- a transaction that starts to count (pending -> approved) must also be checked
        v_becoming_approved := TG_TABLE_NAME = 'transactions'
                               AND (to_jsonb(OLD)->>'status') <> 'approved' AND (to_jsonb(NEW)->>'status') = 'approved';
        IF NEW.project_id IS NOT DISTINCT FROM OLD.project_id AND NEW.event_id IS NOT DISTINCT FROM OLD.event_id
           AND NOT v_becoming_approved THEN
            RETURN NEW;                                           -- nothing that needs the check changed
        END IF;
    END IF;
    IF NEW.project_id IS NOT NULL AND NOT EXISTS
       (SELECT 1 FROM projects WHERE id = NEW.project_id AND approval_status = 'approved' AND deleted_at IS NULL) THEN
        RAISE EXCEPTION 'project is not approved: it must be approved before it can be used here' USING ERRCODE = '23514';
    END IF;
    IF NEW.event_id IS NOT NULL AND NOT EXISTS
       (SELECT 1 FROM events WHERE id = NEW.event_id AND approval_status = 'approved' AND deleted_at IS NULL) THEN
        RAISE EXCEPTION 'event is not approved: it must be approved before it can be used here' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transactions_activity BEFORE INSERT OR UPDATE ON transactions FOR EACH ROW EXECUTE FUNCTION enforce_approved_activity();
CREATE TRIGGER trg_attendances_activity  BEFORE INSERT OR UPDATE ON attendances  FOR EACH ROW EXECUTE FUNCTION enforce_approved_activity();

-- fund_balance — function form of the fund_balances view: approved, non-deleted entries of one fund
CREATE OR REPLACE FUNCTION fund_balance(p_fund UUID) RETURNS NUMERIC
LANGUAGE sql STABLE AS $$
    SELECT COALESCE(SUM(signed_amount(entry_type, amount)), 0)
    FROM transactions
    WHERE fund_id = p_fund AND status = 'approved' AND deleted_at IS NULL;
$$;

-- enforce_ledger_immutability — pending: free; approved: note or void only; rejected/voided: frozen; no deletes after pending
CREATE OR REPLACE FUNCTION enforce_ledger_immutability() RETURNS TRIGGER AS $$
DECLARE
    v_free TEXT[];
BEGIN
    IF TG_OP = 'DELETE' THEN
        IF OLD.status <> 'pending' THEN
            RAISE EXCEPTION 'a % transaction cannot be deleted (void it instead)', OLD.status USING ERRCODE = '42501';
        END IF;
        RETURN OLD;
    END IF;
    IF OLD.status = 'pending' THEN RETURN NEW; END IF;
    -- columns that may change on a non-pending row
    v_free := ARRAY['notes', 'updated_at'];
    IF OLD.status = 'approved' THEN
        IF NEW.status NOT IN ('approved', 'voided') THEN
            RAISE EXCEPTION 'an approved transaction can only be voided, not set to %', NEW.status USING ERRCODE = '42501';
        END IF;
        v_free := v_free || ARRAY['status', 'voided_by', 'voided_at', 'void_reason'];
    END IF;
    IF (to_jsonb(NEW) - v_free) IS DISTINCT FROM (to_jsonb(OLD) - v_free) THEN
        RAISE EXCEPTION 'a % transaction cannot be changed (only notes; approved entries can also be voided)', OLD.status USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transactions_immutable BEFORE UPDATE OR DELETE ON transactions FOR EACH ROW EXECUTE FUNCTION enforce_ledger_immutability();

-- enforce_fund_not_negative — a fund may never go below zero (exactly zero is fine)
-- Checked when an entry starts to count (becomes approved) and when an approved inflow is voided.
CREATE OR REPLACE FUNCTION enforce_fund_not_negative() RETURNS TRIGGER AS $$
DECLARE
    v_fund  UUID;
    v_delta NUMERIC;
BEGIN
    IF TG_OP = 'INSERT' THEN
        IF NEW.status <> 'approved' OR NEW.deleted_at IS NOT NULL THEN RETURN NEW; END IF;
        v_fund := NEW.fund_id;  v_delta := signed_amount(NEW.entry_type, NEW.amount);
    ELSIF OLD.status <> 'approved' AND NEW.status = 'approved' AND NEW.deleted_at IS NULL THEN
        v_fund := NEW.fund_id;  v_delta := signed_amount(NEW.entry_type, NEW.amount);
    ELSIF OLD.status = 'approved' AND OLD.deleted_at IS NULL AND NEW.status = 'voided' THEN
        v_fund := OLD.fund_id;  v_delta := -signed_amount(OLD.entry_type, OLD.amount);
    ELSE
        RETURN NEW;
    END IF;
    IF v_fund IS NULL OR v_delta >= 0 THEN RETURN NEW; END IF;
    PERFORM 1 FROM funds WHERE id = v_fund FOR UPDATE;           -- serialise approvals per fund (no double-spend)
    IF fund_balance(v_fund) + v_delta < 0 THEN
        RAISE EXCEPTION 'insufficient fund balance: % available, % required', fund_balance(v_fund), -v_delta USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_transactions_overdraw BEFORE INSERT OR UPDATE ON transactions FOR EACH ROW EXECUTE FUNCTION enforce_fund_not_negative();

-- =============================================================================
-- VIEWS — derived numbers. Only APPROVED, non-deleted transactions count.
-- security_invoker: row-level security of the caller applies (matters if RLS is used).
-- =============================================================================
CREATE VIEW fund_balances WITH (security_invoker = true) AS
SELECT f.org_id, f.id AS fund_id,
       COALESCE(SUM(signed_amount(t.entry_type, t.amount)) FILTER (WHERE t.status = 'approved'), 0) AS balance
FROM funds f
LEFT JOIN transactions t ON t.fund_id = f.id AND t.org_id = f.org_id AND t.deleted_at IS NULL
WHERE f.deleted_at IS NULL
GROUP BY f.org_id, f.id;

CREATE VIEW project_financials WITH (security_invoker = true) AS
SELECT p.org_id, p.id AS project_id,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'contribution'), 0) AS contributions,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'income'), 0)       AS external_income,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'expense'), 0)      AS expenses,
       COALESCE(SUM(signed_amount(t.entry_type, t.amount)) FILTER (WHERE t.status = 'approved'), 0)      AS net_balance,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'opening_balance'), 0) AS opening_balance,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'refund'), 0)       AS refunds,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type IN ('contribution', 'income', 'opening_balance')), 0)
         - COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'refund'), 0)    AS funding_raised
FROM projects p
LEFT JOIN transactions t ON t.project_id = p.id AND t.org_id = p.org_id AND t.deleted_at IS NULL
WHERE p.deleted_at IS NULL
GROUP BY p.org_id, p.id;

CREATE VIEW event_financials WITH (security_invoker = true) AS
SELECT e.org_id, e.id AS event_id,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'contribution'), 0) AS contributions,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'income'), 0)       AS external_income,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'expense'), 0)      AS expenses,
       COALESCE(SUM(signed_amount(t.entry_type, t.amount)) FILTER (WHERE t.status = 'approved'), 0)      AS net_balance,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'opening_balance'), 0) AS opening_balance,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'refund'), 0)       AS refunds,
       COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type IN ('contribution', 'income', 'opening_balance')), 0)
         - COALESCE(SUM(t.amount) FILTER (WHERE t.status = 'approved' AND t.entry_type = 'refund'), 0)    AS funding_raised
FROM events e
LEFT JOIN transactions t ON t.event_id = e.id AND t.org_id = e.org_id AND t.deleted_at IS NULL
WHERE e.deleted_at IS NULL
GROUP BY e.org_id, e.id;

-- utility_balances: amount_paid = approved expense payments - approved refunds; status derived
CREATE VIEW utility_balances WITH (security_invoker = true) AS
SELECT x.org_id, x.utility_id, x.total_amount, x.amount_paid,
       CASE WHEN x.amount_paid <= 0              THEN 'unpaid'
            WHEN x.amount_paid >= x.total_amount THEN 'paid'
            ELSE 'partial' END AS status
FROM (
    SELECT u.org_id, u.id AS utility_id, u.total_amount,
           COALESCE(SUM(CASE WHEN t.entry_type = 'expense' THEN t.amount ELSE -t.amount END)
                    FILTER (WHERE t.status = 'approved'), 0) AS amount_paid
    FROM utilities u
    LEFT JOIN transactions t ON t.utility_id = u.id AND t.org_id = u.org_id AND t.deleted_at IS NULL
    WHERE u.deleted_at IS NULL
    GROUP BY u.org_id, u.id, u.total_amount
) x;

