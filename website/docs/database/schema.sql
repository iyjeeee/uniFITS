CREATE TRIGGER trg_transactions_review BEFORE INSERT OR UPDATE ON transactions FOR EACH ROW EXECUTE FUNCTION enforce_review_rules();

-- set_transaction_reference — TXN-YYYYMMDD-NNNNNN when the caller gives none (matches the frontend format)
