-- =============================================================================
-- seed_org_defaults — run once when an organization is created.
-- Creates default roles (+ permission sets), payment methods and the settings row.
-- Role sets are DEFAULTS for review; every org can edit them.
-- =============================================================================
CREATE OR REPLACE FUNCTION seed_org_defaults(p_org UUID) RETURNS VOID AS $$
DECLARE
    r RECORD;
BEGIN
    INSERT INTO roles (org_id, name, description, is_system) VALUES
        (p_org, 'Admin',     'Full access to everything',                 TRUE),
        (p_org, 'Secretary', 'Records, projects, events, announcements',  TRUE),
        (p_org, 'Treasurer', 'Funds, transactions and utilities',         TRUE),
        (p_org, 'Auditor',   'Read-only access, reports and audit logs',  TRUE),
        (p_org, 'Member',    'Basic read access',                         TRUE)
    ON CONFLICT (org_id, name) DO NOTHING;

    -- role -> permission keys (Admin gets every key; Treasurer deliberately lacks approve_own_entries)
    FOR r IN SELECT * FROM (VALUES
        ('Secretary', ARRAY['view_members','add_user','edit_user','view_attendance','manage_attendance',
                            'view_projects','add_project','edit_project','approve_project',
                            'view_events','add_event','edit_event','approve_event',
                            'view_funds','view_transactions','view_announcements','post_announcement','edit_announcement','delete_announcement',
                            'view_reports','export_reports','approve_own_entries']),
        ('Treasurer', ARRAY['view_members','view_projects','view_events','view_funds','manage_funds',
                            'view_transactions','add_transaction','approve_transaction','void_transaction',
                            'view_utilities','manage_utilities','view_announcements','view_reports','export_reports']),
        ('Auditor',   ARRAY['view_members','view_attendance','view_projects','view_events','view_funds','view_transactions',
                            'view_utilities','view_announcements','view_reports','export_reports','view_audit_logs']),
        ('Member',    ARRAY['view_projects','view_events','view_announcements'])
    ) AS v(role_name, keys) LOOP
        INSERT INTO role_permissions (role_id, permission_id)
        SELECT ro.id, p.id FROM roles ro JOIN permissions p ON p.key = ANY (r.keys)
        WHERE ro.org_id = p_org AND ro.name = r.role_name
        ON CONFLICT DO NOTHING;
    END LOOP;

    INSERT INTO role_permissions (role_id, permission_id)
    SELECT ro.id, p.id FROM roles ro CROSS JOIN permissions p
    WHERE ro.org_id = p_org AND ro.name = 'Admin'
    ON CONFLICT DO NOTHING;

    INSERT INTO payment_methods (org_id, name, sort_order) VALUES
        (p_org, 'Cash', 1), (p_org, 'GCash', 2), (p_org, 'Bank Transfer', 3), (p_org, 'PayMaya', 4), (p_org, 'Cheque', 5)
    ON CONFLICT (org_id, name) DO NOTHING;

    INSERT INTO settings (org_id) VALUES (p_org) ON CONFLICT (org_id) DO NOTHING;
END; $$ LANGUAGE plpgsql;

