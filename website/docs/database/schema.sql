-- has_permission — does the user's ACTIVE role grant this permission key?
CREATE OR REPLACE FUNCTION has_permission(p_user UUID, p_key TEXT) RETURNS BOOLEAN
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (
        SELECT 1 FROM user_roles ur
        JOIN role_permissions rp ON rp.role_id = ur.role_id
        JOIN permissions p       ON p.id = rp.permission_id
        WHERE ur.user_id = p_user AND ur.is_active AND p.key = p_key);
$$;

-- enforce_review_rules — a reviewer needs the approve_* permission; reviewing your OWN entry also needs approve_own_entries
CREATE OR REPLACE FUNCTION enforce_review_rules() RETURNS TRIGGER AS $$
DECLARE v_key TEXT;
BEGIN
    IF NEW.reviewed_by IS NULL THEN RETURN NEW; END IF;
    IF TG_OP = 'UPDATE' AND NEW.reviewed_by IS NOT DISTINCT FROM OLD.reviewed_by THEN RETURN NEW; END IF;
    v_key := CASE TG_TABLE_NAME WHEN 'projects' THEN 'approve_project'
                                WHEN 'events'   THEN 'approve_event'
                                ELSE 'approve_transaction' END;
    IF NOT has_permission(NEW.reviewed_by, v_key) THEN
        RAISE EXCEPTION 'reviewer lacks permission %', v_key USING ERRCODE = '42501';
    END IF;
    IF NEW.reviewed_by = NEW.created_by AND NOT has_permission(NEW.reviewed_by, 'approve_own_entries') THEN
        RAISE EXCEPTION 'reviewer may not review their own entry (approve_own_entries missing)' USING ERRCODE = '42501';
    END IF;
    RETURN NEW;
END; $$ LANGUAGE plpgsql;

CREATE TRIGGER trg_projects_review     BEFORE INSERT OR UPDATE ON projects     FOR EACH ROW EXECUTE FUNCTION enforce_review_rules();
